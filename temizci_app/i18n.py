def translate_widget_tree(root: Any) -> None:
    """Translate visible Qt widget copy in-place, including dynamic tree rows."""
    from PySide6.QtCore import Qt
    from PySide6.QtWidgets import (
        QAbstractButton,
        QComboBox,
        QDialog,
        QGroupBox,
        QLabel,
        QLineEdit,
        QPlainTextEdit,
        QTabWidget,
        QTreeWidget,
        QWidget,
    )

    widgets = [root, *root.findChildren(QWidget)] if isinstance(root, QWidget) else root.findChildren(QWidget)
    for widget in widgets:
        if isinstance(widget, QDialog):
            widget.setWindowTitle(tr(widget.windowTitle()))
        if isinstance(widget, (QLabel, QAbstractButton)):
            widget.setText(tr(widget.text()))
        if isinstance(widget, QGroupBox):
            widget.setTitle(tr(widget.title()))
        if isinstance(widget, QComboBox):
            for index in range(widget.count()):
                widget.setItemText(index, tr(widget.itemText(index)))
                tip = widget.itemData(index, Qt.ItemDataRole.ToolTipRole)
                if tip:
                    widget.setItemData(index, tr(tip), Qt.ItemDataRole.ToolTipRole)
        if isinstance(widget, (QLineEdit, QPlainTextEdit)):
            widget.setPlaceholderText(tr(widget.placeholderText()))
        if isinstance(widget, QWidget) and widget.toolTip():
            widget.setToolTip(tr(widget.toolTip()))
        if isinstance(widget, QTabWidget):
            for index in range(widget.count()):
                widget.setTabText(index, tr(widget.tabText(index)))
        if isinstance(widget, QTreeWidget):
            header = widget.headerItem()
            if header:
                for column in range(widget.columnCount()):
                    header.setText(column, tr(header.text(column)))
            for index in range(widget.topLevelItemCount()):
                _translate_tree_item(widget.topLevelItem(index), tr)


def _translate_tree_item(item: Any, translate) -> None:
    for column in range(item.columnCount()):
        item.setText(column, translate(item.text(column)))
    for index in range(item.childCount()):
        _translate_tree_item(item.child(index), translate)
